"""Send backtest results to Telegram."""
import requests
import sys

TOKEN = "TELEGRAM_BOT_TOKEN_REDACTED"
CHAT_ID = "TELEGRAM_CHAT_ID_REDACTED"


def send(msg):
    url = f"https://api.telegram.org/bot{TOKEN}/sendMessage"
    # Split into chunks of 4000 chars
    chunks = []
    current = ""
    for line in msg.split("\n"):
        if len(current) + len(line) + 1 > 4000:
            chunks.append(current)
            current = ""
        current += line + "\n"
    if current:
        chunks.append(current)

    for chunk in chunks:
        resp = requests.post(url, json={
            "chat_id": CHAT_ID,
            "text": chunk,
            "parse_mode": "HTML",
            "disable_web_page_preview": True,
        }, timeout=15)
        print(f"  Sent chunk ({len(chunk)} chars): {'OK' if resp.ok else 'FAIL'}")
    return True


